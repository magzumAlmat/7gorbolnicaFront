function FaqBlocks({ blocks }) {
  return (
    <>
      {blocks.map((block, bi) => {
        if (block.type === 'ol') {
          return (
            <Box
              key={bi}
              component="ol"
              sx={{ m: 0, mb: 1, pl: 3, fontSize: '1rem', lineHeight: 1.9, color: '#334155' }}
            >
              {block.items.map((item, ii) => (
                <Box component="li" key={ii} sx={{ mb: 0.5 }}>
                  {item}
                </Box>
              ))}
            </Box>
          );
        }
        if (block.type === 'ul') {
          return (
            <Box
              key={bi}
              component="ul"
              sx={{ m: 0, mb: 1, pl: 3, fontSize: '1rem', lineHeight: 1.9, color: '#334155' }}
            >
              {block.items.map((item, ii) => (
                <Box component="li" key={ii} sx={{ mb: 0.5 }}>
                  {item}
                </Box>
              ))}
            </Box>
          );
        }
        return (
          <Typography key={bi} sx={{ fontSize: '1rem', lineHeight: 1.9, color: '#334155', mb: 1, '&:last-child': { mb: 0 } }}>
            {block.text}
          </Typography>
        );
      })}
    </>
  );
}

